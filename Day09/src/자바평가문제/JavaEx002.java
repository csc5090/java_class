package 자바평가문제;

public class JavaEx002 {

	// 자바평가문제 1) 이중 for 반복문을 사용하여 다음과 같은 출력 결과물이 나오는 코드를 작성해본다.
	// 출력 예) # # #
	// # # #
	// # # #

	public static void main(String[] args) {

		for (int a = 1; a <= 3; a++) {
			System.out.print("");
			for (int b = 1; b <= 3; b++) {
				System.out.print(" #");
			}
			System.out.println();
		}
	}
	
	
	
	
	
	
	
	
	

}
