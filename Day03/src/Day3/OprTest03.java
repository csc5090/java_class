package Day3;

public class OprTest03 {

	public static void main(String[] args) {
		
		boolean flag = true;
		
		System.out.printf("flag = %b \n", flag); //true
		System.out.printf("!true = %b \n", !flag); //!true -> false
		System.out.printf("!!ture = %b \n", !!flag); //!true ->!false -> true
		
		

	}

}
